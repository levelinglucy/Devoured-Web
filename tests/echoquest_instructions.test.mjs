import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { runInNewContext } from "node:vm";

// Verify the instructions shown to visitors describe the *implemented*
// predicates. No real browser storage or Firebase calls are made here.
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(join(root, "echoquest.js"), "utf8");
const now = 1_800_000_000_000;

function evaluate(path, fragments = [], initial = {}) {
  const records = new Map(Object.entries(initial));
  const writes = [];
  const context = {
    getSigilPath: () => ({ id: path }),
    getFragments: () => fragments,
    getSigilHistory: () => [],
    Date: { now: () => now },
    localStorage: {
      getItem(key) { return records.get(key) ?? null; },
      setItem(key, value) {
        writes.push(key);
        records.set(key, String(value));
      }
    }
  };
  runInNewContext(source.replace(/^\s*import\s+.*?;\s*$/gm, "")
    .replace(/\bexport\s+(?=function)/g, "") +
    "\nthis.getEchoquest = getEchoquest;", context);
  return { quest: context.getEchoquest(), records, writes };
}

test("Witness instructions describe fragments, not an untracked force visit", () => {
  const before = evaluate("witness", [{}, {}]);
  const after = evaluate("witness", [{}, {}, {}]);
  assert.equal(before.quest.complete, false);
  assert.equal(after.quest.complete, true);
  assert.match(after.quest.task, /at least 3 fragments/i);
  assert.doesNotMatch(after.quest.task, /force(?:\.html)?/i);
  assert.deepEqual(after.writes, []);
});

test("Lost instructions identify opening Echoquest as the timer's origin", () => {
  const first = evaluate("lost");
  assert.equal(first.quest.complete, false);
  assert.equal(first.records.get("lostVisit"), String(now));
  assert.deepEqual(first.writes, ["lostVisit"]);
  assert.match(first.quest.task, /opening this quest/i);
  assert.doesNotMatch(first.quest.task, /visit fragments(?:\.html)?/i);

  const later = evaluate("lost", [], { lostVisit: String(now - 86_400_000) });
  assert.equal(later.quest.complete, true);
  assert.deepEqual(later.writes, []);
});

test("Unwired Fire and Split milestones are described without a dead redirect", () => {
  for (const path of ["fire", "split"]) {
    const state = evaluate(path);
    assert.equal(state.quest.complete, false);
    assert.match(state.quest.task, /not generated by this build/i);
    assert.doesNotMatch(state.quest.task, /glitch\.html/i);
    assert.deepEqual(state.writes, []);
  }
  // Existing milestone flags still work; this copy-only repair must not
  // reinterpret or erase previously saved, even manually seeded, progress.
  assert.equal(evaluate("fire", [], { echoCount: "5", glitchTrigger: "true" }).quest.complete, true);
  assert.equal(evaluate("split", [], { mirrorLoop: "true" }).quest.complete, true);
});
